const fs = require("fs");
const path = require("path");
const assert = require("assert");

const htmlPath = path.join(__dirname, "..", "03-ui-prototype", "prototype", "pages", "intelligent-config.html");
const html = fs.readFileSync(htmlPath, "utf8");
const callsPanel = html.match(/<section class="config-panel" data-config-panel="calls"[\s\S]*?<section class="config-panel" data-config-panel="tokens"/)?.[0] || "";
const callModal = html.match(/<div class="modal-mask" data-modal="callRecordModal"[\s\S]*?<div class="modal-mask" data-modal="knowledgeFileModal"/)?.[0] || "";

assert(callsPanel.includes("<h3>Agent 调用记录</h3>"), "调用记录页标题应明确为 Agent 调用记录");
assert(callsPanel.includes("记录每次 Agent 调用，以及 Agent 执行过程中调用知识库和模型的情况。"), "调用记录说明应聚焦 Agent 调用、知识库和模型");
assert(callsPanel.includes("保留全部历史记录"), "调用记录页应保留全部历史记录");
assert(!callsPanel.includes("保留最近 30 天") && !callsPanel.includes("筛选范围最多 30 天") && !callsPanel.includes("时间范围不超过 30 天"), "调用记录页不应限制为最近 30 天");
assert(!callsPanel.includes("<option>全部调用类型</option>"), "调用记录筛选区不应展示全部调用类型筛选");
assert(callsPanel.includes("<td>Agent 调用</td>"), "调用记录列表应展示 Agent 调用类型记录");
assert(callsPanel.includes("<td>知识库检索</td>"), "调用记录列表应展示知识库检索类型记录");
assert(callsPanel.includes("<td>模型调用</td>"), "调用记录列表应展示模型调用类型记录");
assert(callsPanel.includes("<option>成功</option>") && callsPanel.includes("<option>失败</option>") && callsPanel.includes("<option>超时</option>"), "调用状态应覆盖成功、失败和超时");
assert(!callsPanel.includes("部分成功"), "调用记录状态不应展示部分成功，辅助步骤异常应进入详情");
assert(!callsPanel.includes("低置信度"), "调用记录状态不应展示低置信度");
assert(callsPanel.includes('data-call-detail="knowledge"'), "知识库检索记录应绑定知识库检索详情");
assert(callsPanel.includes('data-call-detail="agent"'), "Agent 调用记录应绑定 Agent 调用详情");
assert(callsPanel.includes('data-call-detail="model"'), "模型调用记录应绑定模型调用详情");
assert(callsPanel.includes('data-call-detail="agentFailed"'), "失败记录应绑定失败详情");
assert(callsPanel.includes('data-call-detail="modelTimeout"'), "超时记录应绑定超时详情");
assert(callsPanel.includes("触发入口"), "列表列名应使用实际触发入口，不应继续写触发来源");
assert(callsPanel.includes("设备详情页 / 故障诊断") && callsPanel.includes("全局助手浮窗 / 故障上报") && callsPanel.includes("驾驶舱 BI / 维修效率看板"), "触发入口应展示实际业务入口");
assert(!callsPanel.includes("<td>故障诊断 Agent</td><td><span class=\"status ok\">成功</span>"), "触发入口不应直接写执行 Agent 名称");
assert(callsPanel.includes('class="table-wrap call-record-table-wrap"'), "调用记录列表应使用专门的可滚动表格容器");
assert(callsPanel.includes('class="call-pagination"'), "调用记录列表应展示分页控件");
assert(!/业务工具调用|问数业务查询摘要|RAGFlow 同步\/处理|知识库配置/.test(callsPanel), "调用记录列表不应展示业务工具调用或配置处理日志");
assert(!/<td>查询改写<\/td>/.test(callsPanel), "查询改写不应作为列表一级调用类型展示");
assert(!callsPanel.includes("系统操作知识库配置保存"), "知识库配置保存失败不应出现在 Agent 调用记录列表");
assert(callModal.includes('class="config-modal call-detail-modal"'), "调用详情弹窗应使用专门的详情布局");
assert(callModal.includes("Agent 调用详情"), "调用详情标题应说明是 Agent 调用详情");
assert(callModal.includes("data-call-detail-body"), "调用详情内容应由当前记录类型渲染");
assert(!callModal.includes("脱敏原文") && !callModal.includes("data-toggle-fulltext") && !callModal.includes("data-fulltext"), "调用详情不应展示脱敏原文入口");
assert(html.includes("const callDetailTemplates"), "应提供不同调用类型的详情模板");
assert(html.includes("renderCallRecordDetail"), "打开调用详情时应按记录类型渲染内容");
assert(html.includes("检索明细"), "知识库检索类型详情应展示检索明细");
assert(html.includes("执行结果"), "未涉及知识库的 Agent 调用应展示执行结果而不是检索明细");
assert(html.includes("模型调用明细"), "模型调用类型详情应展示模型调用明细");
assert(html.includes("辅助步骤异常"), "辅助步骤异常应在详情中展示，不作为列表一级状态");
assert(html.includes("异常原因与处理建议"), "失败和超时详情应展示异常原因与处理建议");
assert(html.includes("call-step is-error") && html.includes("call-step is-timeout"), "失败和超时详情应在执行链路中标出具体异常步骤");
assert(html.includes("绑定模型未启用") && html.includes("等待 10s 未返回"), "失败和超时详情应展示具体原因");
assert(html.includes("设备详情页 / 故障诊断") && html.includes("全局助手浮窗 / 故障上报"), "详情页也应展示实际触发入口");
assert(html.includes(".call-record-table-wrap") && html.includes("position: sticky") && html.includes(".call-pagination"), "调用记录长列表应支持表头锁定和分页样式");
assert(html.includes("data-call-timeline"), "调用详情应提供时间线结构");
assert(html.includes("data-call-lookup-detail"), "知识库检索详情应提供检索明细结构");

console.log("intelligent-config call record checks passed");
